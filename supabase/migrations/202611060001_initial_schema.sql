create function public.adjust_inventory(
  p_product_id bigint,
  p_quantity_change integer,
  p_reason text,
  p_note text default ''
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_stock integer;
begin
  if not (select public.is_admin()) then
    raise exception 'Only administrators can adjust inventory.' using errcode = '42501';
  end if;
  if p_quantity_change is null or p_quantity_change = 0 then
    raise exception 'Enter a non-zero inventory adjustment.' using errcode = '22023';
  end if;
  if length(trim(coalesce(p_reason, ''))) = 0 then
    raise exception 'Enter a reason for the inventory adjustment.' using errcode = '22023';
  end if;

  update public.products
  set stock_quantity = stock_quantity + p_quantity_change
  where id = p_product_id
    and stock_quantity + p_quantity_change >= 0
  returning stock_quantity into v_stock;

  if not found then
    raise exception 'Product not found or the adjustment would make stock negative.'
      using errcode = '22023';
  end if;

  insert into public.inventory_movements (
    product_id, changed_by, quantity_change, reason, note
  ) values (
    p_product_id, (select auth.uid()), p_quantity_change,
    trim(p_reason), coalesce(trim(p_note), '')
  );

  return v_stock;
end;
$$;

revoke all on function public.adjust_inventory(bigint, integer, text, text) from public;
