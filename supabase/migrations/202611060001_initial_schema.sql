-- AquaShield's first shared database schema.
-- This migration targets Supabase PostgreSQL and is used by the Supabase-backed
-- storefront when its project URL and publishable key are configured.

create type public.account_role as enum ('buyer', 'admin');
create type public.order_type as enum ('retail', 'organization');
create type public.order_status as enum (
  'awaiting_payment',
  'processing',
  'packed',
  'shipped',
  'out_for_delivery',
  'delivered',
  'cancelled'
);
create type public.payment_method as enum ('gcash', 'maya', 'cash_on_delivery');
create type public.payment_status as enum ('pending', 'paid', 'failed', 'refunded');
create type public.delivery_method as enum (
  'standard_nationwide',
  'priority_dispatch',
  'barangay_hub_pickup'
);

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  first_name text not null default '',
  last_name text not null default '',
  username text unique,
  role public.account_role not null default 'buyer',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_username_format check (
    username is null or username ~ '^[A-Za-z0-9_]{3,20}$'
  )
);

create unique index profiles_username_case_insensitive_idx
  on public.profiles (lower(username))
  where username is not null;

create table public.categories (
  id bigint generated by default as identity primary key,
  parent_id bigint references public.categories (id) on delete restrict,
  name text not null,
  slug text not null unique,
  description text,
  display_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint categories_name_not_blank check (length(trim(name)) > 0),
  constraint categories_not_own_parent check (parent_id is null or parent_id <> id)
);

create table public.products (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.categories (id) on delete restrict,
  sku text unique,
  name text not null,
  description text not null default '',
  price numeric(12, 2) not null check (price >= 0),
  organization_minimum_quantity integer not null default 20
    check (organization_minimum_quantity >= 1),
  stock_quantity integer not null default 0 check (stock_quantity >= 0),
  is_kit_bag boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint products_name_not_blank check (length(trim(name)) > 0)
);

create index products_category_active_idx
  on public.products (category_id, is_active, name);
create unique index products_single_kit_bag_idx
  on public.products (is_kit_bag)
  where is_kit_bag;

create table public.product_images (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products (id) on delete cascade,
  storage_path text not null,
  alt_text text not null default '',
  display_order integer not null default 0,
  is_primary boolean not null default false,
  created_at timestamptz not null default now(),
  constraint product_images_storage_path_unique unique (storage_path)
);

create unique index product_images_one_primary_per_product_idx
  on public.product_images (product_id)
  where is_primary;

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique default (
    'ASR-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8))
  ),
  buyer_id uuid not null references public.profiles (id) on delete restrict,
  order_type public.order_type not null default 'retail',
  status public.order_status not null default 'processing',
  payment_method public.payment_method not null,
  payment_status public.payment_status not null default 'pending',
  delivery_method public.delivery_method not null,
  contact_name text not null,
  email text not null,
  phone text not null,
  address_line1 text not null,
  address_line2 text not null default '',
  city text not null,
  province text not null,
  postal_code text not null default '',
  subtotal numeric(12, 2) not null default 0 check (subtotal >= 0),
  vat_amount numeric(12, 2) not null default 0 check (vat_amount >= 0),
  shipping_amount numeric(12, 2) not null default 0 check (shipping_amount >= 0),
  total numeric(12, 2) not null default 0 check (total >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint orders_contact_name_not_blank check (length(trim(contact_name)) > 0),
  constraint orders_email_not_blank check (length(trim(email)) > 0),
  constraint orders_phone_not_blank check (length(trim(phone)) > 0),
  constraint orders_address_not_blank check (length(trim(address_line1)) > 0),
  constraint orders_city_not_blank check (length(trim(city)) > 0),
  constraint orders_province_not_blank check (length(trim(province)) > 0)
);

create index orders_buyer_created_idx on public.orders (buyer_id, created_at desc);
create index orders_status_created_idx on public.orders (status, created_at desc);

create table public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders (id) on delete cascade,
  product_id bigint references public.products (id) on delete set null,
  product_name_snapshot text not null,
  sku_snapshot text,
  unit_price numeric(12, 2) not null check (unit_price >= 0),
  quantity integer not null check (quantity > 0),
  line_total numeric(12, 2) not null check (line_total >= 0),
  kit_group_id uuid,
  is_gift boolean not null default false,
  created_at timestamptz not null default now()
);

create index order_items_order_idx on public.order_items (order_id);

create table public.inventory_movements (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products (id) on delete restrict,
  order_id uuid references public.orders (id) on delete set null,
  changed_by uuid references public.profiles (id) on delete set null,
  quantity_change integer not null check (quantity_change <> 0),
  reason text not null,
  note text not null default '',
  created_at timestamptz not null default now(),
  constraint inventory_reason_not_blank check (length(trim(reason)) > 0)
);

create index inventory_movements_product_created_idx
  on public.inventory_movements (product_id, created_at desc);

create table public.order_status_events (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders (id) on delete cascade,
  status public.order_status not null,
  note text not null default '',
  changed_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now()
);

create index order_status_events_order_created_idx
  on public.order_status_events (order_id, created_at);

