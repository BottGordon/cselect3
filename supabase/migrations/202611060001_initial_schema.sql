-- Creating orders validates the cart against current product data, locks stock
-- rows, snapshots prices, and records inventory changes within one transaction.
create function public.place_order(
  p_items jsonb,
  p_order_type public.order_type,
  p_payment_method public.payment_method,
  p_delivery_method public.delivery_method,
  p_contact_name text,
  p_phone text,
  p_address_line1 text,
  p_address_line2 text,
  p_city text,
  p_province text,
  p_postal_code text default '',
  p_kit_product_ids bigint[] default '{}'::bigint[],
  p_kit_quantity integer default 0,
  p_kit_has_free_bag boolean default false
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_buyer_id uuid := (select auth.uid());
  v_order_id uuid := gen_random_uuid();
  v_item jsonb;
  v_product public.products%rowtype;
  v_product_id bigint;
  v_quantity integer;
  v_unit_price numeric(12, 2);
  v_line_total numeric(12, 2);
  v_subtotal numeric(12, 2) := 0;
  v_vat numeric(12, 2);
  v_shipping numeric(12, 2);
  v_status public.order_status;
  v_kit_product_id bigint;
  v_kit_group_id uuid;
  v_kit_discount numeric(4, 2);
begin
  if v_buyer_id is null then
    raise exception 'Sign in before placing an order.' using errcode = '28000';
  end if;
  if coalesce(jsonb_typeof(p_items), '') <> 'array' then
    raise exception 'Cart items must be sent as a list.' using errcode = '22023';
  end if;
  if jsonb_array_length(p_items) = 0 and coalesce(p_kit_quantity, 0) = 0 then
    raise exception 'Your cart is empty.' using errcode = '22023';
  end if;
  if exists (
    select 1
    from jsonb_array_elements(p_items) as item(value)
    where coalesce(item.value ->> 'product_id', '') !~ '^[0-9]+$'
      or coalesce(item.value ->> 'quantity', '') !~ '^[0-9]+$'
  ) then
    raise exception 'Cart items need a valid product and quantity.' using errcode = '22023';
  end if;
  if exists (
    select 1
    from jsonb_array_elements(p_items) as item(value)
    group by item.value ->> 'product_id'
    having count(*) > 1
  ) then
    raise exception 'Each product must appear only once in the cart.' using errcode = '22023';
  end if;
  if coalesce(p_kit_quantity, 0) < 0
    or (coalesce(p_kit_quantity, 0) = 0 and cardinality(coalesce(p_kit_product_ids, '{}'::bigint[])) <> 0)
    or (coalesce(p_kit_quantity, 0) > 0 and cardinality(coalesce(p_kit_product_ids, '{}'::bigint[])) not between 7 and 15) then
    raise exception 'A custom Go-Bag must include 7 to 15 selected products.' using errcode = '22023';
  end if;
  if coalesce(p_kit_quantity, 0) > 0
    and cardinality(array(select distinct unnest(coalesce(p_kit_product_ids, '{}'::bigint[]))))
      <> cardinality(p_kit_product_ids) then
    raise exception 'A Go-Bag cannot contain the same product more than once.' using errcode = '22023';
  end if;
  if p_order_type = 'retail'::public.order_type
    and coalesce(p_kit_quantity, 0) > 0
    and (p_kit_quantity <> 1 or not coalesce(p_kit_has_free_bag, false)) then
    raise exception 'Solo Go-Bags are sold one at a time with their included dry bag.' using errcode = '22023';
  end if;
  if p_order_type = 'organization'::public.order_type
    and coalesce(p_kit_quantity, 0) > 0
    and (p_kit_quantity < 20 or coalesce(p_kit_has_free_bag, false)) then
    raise exception 'Organization Go-Bags require at least 20 kits.' using errcode = '22023';
  end if;
  if coalesce(p_kit_quantity, 0) = 0 and coalesce(p_kit_has_free_bag, false) then
    raise exception 'An included dry bag must belong to a Go-Bag order.' using errcode = '22023';
  end if;
  if length(trim(coalesce(p_contact_name, ''))) = 0
    or length(trim(coalesce(p_phone, ''))) = 0
    or length(trim(coalesce(p_address_line1, ''))) = 0
    or length(trim(coalesce(p_city, ''))) = 0
    or length(trim(coalesce(p_province, ''))) = 0 then
    raise exception 'Complete all required delivery details.' using errcode = '22023';
  end if;

  v_shipping := case p_delivery_method
    when 'standard_nationwide' then 150
    when 'priority_dispatch' then 250
    when 'barangay_hub_pickup' then 0
  end;
  if v_shipping is null then
    raise exception 'Choose a valid delivery method.' using errcode = '22023';
  end if;

  -- Acquire every needed stock lock in one stable order to reduce deadlocks.
  perform product.id
  from public.products as product
  where product.id = any(coalesce(p_kit_product_ids, '{}'::bigint[]))
    or product.id in (
      select (item.value ->> 'product_id')::bigint
      from jsonb_array_elements(p_items) as item(value)
    )
    or (coalesce(p_kit_has_free_bag, false) and product.is_kit_bag)
  order by product.id
  for update;

  v_status := case
    when p_payment_method = 'cash_on_delivery'::public.payment_method
      then 'processing'::public.order_status
    else 'awaiting_payment'::public.order_status
  end;

  insert into public.orders (
    id, buyer_id, order_type, status, payment_method, delivery_method,
    contact_name, email, phone, address_line1, address_line2, city,
    province, postal_code, shipping_amount
  ) values (
    v_order_id, v_buyer_id, p_order_type, v_status, p_payment_method,
    p_delivery_method, trim(p_contact_name),
    coalesce((select auth.jwt() ->> 'email'), ''), trim(p_phone),
    trim(p_address_line1), coalesce(trim(p_address_line2), ''), trim(p_city),
    trim(p_province), coalesce(trim(p_postal_code), ''), v_shipping
  );

  for v_item in
    select item.value
    from jsonb_array_elements(p_items) as item(value)
    order by case
      when coalesce(item.value ->> 'product_id', '') ~ '^[0-9]+$'
        then (item.value ->> 'product_id')::bigint
      else 9223372036854775807
    end
  loop
    v_product_id := (v_item ->> 'product_id')::bigint;
    v_quantity := (v_item ->> 'quantity')::integer;
    if v_quantity < 1 then
      raise exception 'Product quantities must be at least one.' using errcode = '22023';
    end if;

    select * into v_product
    from public.products
    where id = v_product_id and is_active;
    if not found then
      raise exception 'A product in your cart is unavailable.' using errcode = 'P0002';
    end if;
    if v_product.stock_quantity < v_quantity then
      raise exception 'Not enough stock for %.', v_product.name using errcode = 'P0001';
    end if;
    if p_order_type = 'organization'::public.order_type
      and v_quantity < v_product.organization_minimum_quantity then
      raise exception '% requires an organization order of at least % units.',
        v_product.name, v_product.organization_minimum_quantity using errcode = '22023';
    end if;

    v_unit_price := v_product.price;
    if p_order_type = 'organization'::public.order_type then
      v_unit_price := round(v_product.price * case
        when v_quantity >= 100 then 0.85
        when v_quantity >= 50 then 0.90
        else 0.95
      end, 2);
    end if;
    v_line_total := v_unit_price * v_quantity;
    v_subtotal := v_subtotal + v_line_total;

    update public.products
    set stock_quantity = stock_quantity - v_quantity
    where id = v_product.id;

    insert into public.order_items (
      order_id, product_id, product_name_snapshot, sku_snapshot,
      unit_price, quantity, line_total
    ) values (
      v_order_id, v_product.id, v_product.name, v_product.sku,
      v_unit_price, v_quantity, v_line_total
    );

    insert into public.inventory_movements (
      product_id, order_id, changed_by, quantity_change, reason
    ) values (
      v_product.id, v_order_id, v_buyer_id, -v_quantity, 'order_reserved'
    );
  end loop;

  if coalesce(p_kit_quantity, 0) > 0 then
    v_kit_group_id := gen_random_uuid();
    v_kit_discount := case
      when p_order_type = 'retail'::public.order_type then 0.10
      when p_kit_quantity >= 100 then 0.15
      when p_kit_quantity >= 50 then 0.10
      else 0.05
    end;

    for v_kit_product_id in
      select unnest(coalesce(p_kit_product_ids, '{}'::bigint[])) order by 1
    loop
      select * into v_product
      from public.products
      where id = v_kit_product_id and is_active;
      if not found then
        raise exception 'A product in your Go-Bag is unavailable.' using errcode = 'P0002';
      end if;
      if v_product.stock_quantity < p_kit_quantity then
        raise exception 'Not enough stock for %.', v_product.name using errcode = 'P0001';
      end if;

      v_unit_price := v_product.price;
      v_line_total := round(v_product.price * (1 - v_kit_discount), 2) * p_kit_quantity;
      v_subtotal := v_subtotal + v_line_total;

      update public.products
      set stock_quantity = stock_quantity - p_kit_quantity
      where id = v_product.id;

      insert into public.order_items (
        order_id, product_id, product_name_snapshot, sku_snapshot,
        unit_price, quantity, line_total, kit_group_id
      ) values (
        v_order_id, v_product.id, v_product.name, v_product.sku,
        v_unit_price, p_kit_quantity, v_line_total, v_kit_group_id
      );

      insert into public.inventory_movements (
        product_id, order_id, changed_by, quantity_change, reason
      ) values (
        v_product.id, v_order_id, v_buyer_id, -p_kit_quantity, 'go_bag_reserved'
      );
    end loop;

    if coalesce(p_kit_has_free_bag, false) then
      select * into v_product
      from public.products
      where is_kit_bag and is_active;
      if not found then
        raise exception 'The included Go-Bag dry bag is not configured.' using errcode = 'P0002';
      end if;
      if v_product.stock_quantity < p_kit_quantity then
        raise exception 'Not enough stock for the included Go-Bag dry bag.' using errcode = 'P0001';
      end if;

      update public.products
      set stock_quantity = stock_quantity - p_kit_quantity
      where id = v_product.id;

      insert into public.order_items (
        order_id, product_id, product_name_snapshot, sku_snapshot,
        unit_price, quantity, line_total, kit_group_id, is_gift
      ) values (
        v_order_id, v_product.id, v_product.name, v_product.sku,
        0, p_kit_quantity, 0, v_kit_group_id, true
      );

      insert into public.inventory_movements (
        product_id, order_id, changed_by, quantity_change, reason
      ) values (
        v_product.id, v_order_id, v_buyer_id, -p_kit_quantity, 'go_bag_gift_reserved'
      );
    end if;
  end if;

  v_vat := round(v_subtotal * 0.12, 2);
  update public.orders
  set subtotal = v_subtotal,
      vat_amount = v_vat,
      total = v_subtotal + v_vat + v_shipping
  where id = v_order_id;

  return v_order_id;
end;
$$;

