  on public.inventory_movements for select to authenticated
  using ((select public.is_admin()));
create policy "Admins can manage inventory movements"
  on public.inventory_movements for all to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

create policy "Buyers can read their order status and admins can read all"
  on public.order_status_events for select to authenticated
  using (
    exists (
      select 1 from public.orders
      where orders.id = order_status_events.order_id
        and (orders.buyer_id = (select auth.uid()) or (select public.is_admin()))
    )
  );
create policy "Admins can manage order status history"
  on public.order_status_events for all to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

